package map;

/**
 * 题目覆盖：
 * 1. HashMap链表发生转换后为什么不用平衡二叉树?
 * 2. 为什么HashMap要用红黑树而不是平衡二叉树?
 *
 * 核心考点与算法级理论剖析：
 *
 * 一、什么是平衡二叉树（AVL 树）？
 * 1. 定义：AVL 树是【严格平衡二叉查找树】。
 * 2. 核心约束：任何节点的左子树与右子树的高度差（平衡因子 Balance Factor）绝对值严禁超过 1（BF ∈ {-1, 0, 1}）。
 * 3. 树高上限：最大高度严格控制在约 1.44 log2(n)。
 * 4. 优缺点：
 *    - 优势：树体结构极度扁平匀称，纯粹查询时的比较次数最少，查询性能达到二叉树极致；
 *    - 致命缺陷：因追求极致平衡，在执行插入（insert）和删除（delete）操作时极易打破平衡，
 *      必须频繁进行单旋（LL/RR）或双旋（LR/RL）自平衡调整。
 *      在最坏情况下，删除一个节点可能需要向上回溯多层，进行 O(log n) 次旋转调整，维护开销极大。
 *
 * 二、什么是红黑树（Red-Black Tree）？
 * 1. 定义：红黑树是【弱平衡二叉查找树】（折中平衡）。
 * 2. 五大核心准则：
 *    - 准则 1：每个节点要么是红色，要么是黑色；
 *    - 准则 2：根节点（Root）永远是黑色；
 *    - 准则 3：所有叶子节点（NIL 哨兵空节点）都是黑色；
 *    - 准则 4：红色节点的两个子节点必须都是黑色（即绝不允许出现连续的红色节点）；
 *    - 准则 5：从任一节点到其每个叶子节点的所有路径，必须包含相同数目的黑色节点（黑色高度相同）。
 * 3. 树高特征：从根到叶子的最长路径（红黑交替）绝不会超过最短路径（全黑）的 2 倍，树高上限约为 2 log2(n + 1)。
 *
 * 三、为什么 HashMap 选用红黑树而不是 AVL 树？（核心权衡 Trade-Off）：
 * 1. 查询性能差距在实际场景下微乎其微：
 *    - HashMap 单个桶发生树化时，节点数量通常只有 8 到几十个。
 *    - 在小数据量级别下，AVL 树的 1.44 log2(n) 与红黑树的 2 log2(n) 的查找比较次数最多只相差 1 ~ 2 次，
 *      在 CPU 纳秒级执行中差异微乎其微。
 * 2. 插入与删除时的旋转自平衡维护成本悬殊：
 *    - AVL 树：插入最多需 2 次旋转，但删除节点时最多可能需要高达 O(log n) 次连环旋转重平衡；
 *    - 红黑树：通过引入节点颜色，大部分失衡仅需通过廉价的【节点变色（O(1) 内存位赋值）】即可修复；
 *      红黑树的插入操作【最多只需 2 次旋转】，删除操作【最多只需 3 次旋转】即可彻底恢复平衡！
 * 3. 结论：
 *    - HashMap 是一个读写均高频的通用键值对容器。
 *    - AVL 树适合“只读/读极多写极少”的静态字典；
 *    - 红黑树在插入、删除与查询之间的综合性能折中表现，远胜于 AVL 树。
 */
